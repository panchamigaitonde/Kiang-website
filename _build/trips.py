    facts += f'<div><div class="label">Price</div><div class="value">{price}</div></div>'
    f = t["feature"]
    if "video" in f:
        media = f"""<div class="feature-media tall"><video autoplay muted loop playsinline preload="metadata" poster="images/{f['poster']}.jpg" aria-label="A snow leopard filmed in Spiti">
          <source src="images/{f['video']}.webm" type="video/webm"><source src="images/{f['video']}.mp4" type="video/mp4"></video></div>"""
    else:
        media = f'<div class="feature-media wide">{pic(f["image"], "A Great Indian Bustard in Desert National Park")}</div>'
